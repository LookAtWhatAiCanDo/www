#!/usr/bin/env node
/**
 * fetch-projects.js
 * Run by GitHub Actions on a schedule.
 * Fetches all public repos from the LookAtWhatAiCanDo org,
 * plus selected external repos,
 * and writes public/data/projects.json for the static site.
 */

const fs = require('fs');
const path = require('path');

const ORG = 'LookAtWhatAiCanDo';
const TOKEN = process.env.GITHUB_TOKEN;
const OUTPUT = path.join(__dirname, '..', 'public', 'data', 'projects.json');

// Repos to always exclude (forks, meta repos, etc.)
const EXCLUDE = [];

// Additional public repositories to show in the Projects area.
// Use owner/repo strings so the list stays easy to review in pull requests.
const EXTRA_REPOS = [
  'SmartFoo/smartfoo',
  'swooby/Parropeato'
];

const headers = {
  Accept: 'application/vnd.github+json',
  'X-GitHub-Api-Version': '2022-11-28',
  'User-Agent': 'LookAtWhatAiCanDo-site-builder'
};

if (TOKEN) {
  headers['Authorization'] = `Bearer ${TOKEN}`;
} else {
  console.warn('⚠️  No GITHUB_TOKEN set — rate limits will be tight');
}

function repoToProject(r) {
  return {
    name: r.name,
    owner: r.owner?.login || null,
    fullName: r.full_name || null,
    description: r.description || null,
    url: r.html_url,
    homepage: r.homepage || null,
    language: r.language || null,
    stars: r.stargazers_count,
    forks: r.forks_count,
    watchers: r.watchers_count,
    topics: r.topics || [],
    updatedAt: r.updated_at,
    createdAt: r.created_at,
    openIssues: r.open_issues_count
  };
}

async function fetchJson(url) {
  const res = await fetch(url, { headers });

  if (!res.ok) {
    const body = await res.text();
    throw new Error(`GitHub API error ${res.status}: ${body}`);
  }

  return res.json();
}

async function fetchOrgRepos() {
  const url = `https://api.github.com/orgs/${ORG}/repos?per_page=100&sort=updated&type=public`;
  console.log(`→ Fetching repos for org: ${ORG}`);

  return fetchJson(url);
}

async function fetchExtraRepos() {
  if (EXTRA_REPOS.length === 0) return [];

  console.log(`→ Fetching extra repos: ${EXTRA_REPOS.join(', ')}`);

  return Promise.all(EXTRA_REPOS.map(fullName => {
    const [owner, repo] = fullName.split('/');
    if (!owner || !repo) {
      throw new Error(`Invalid EXTRA_REPOS entry "${fullName}". Expected "owner/repo".`);
    }

    return fetchJson(`https://api.github.com/repos/${owner}/${repo}`);
  }));
}

async function fetchRepos() {
  const [orgRepos, extraRepos] = await Promise.all([
    fetchOrgRepos(),
    fetchExtraRepos()
  ]);

  const reposByFullName = new Map();

  for (const repo of [...orgRepos, ...extraRepos]) {
    if (repo.private || repo.fork || EXCLUDE.includes(repo.name) || EXCLUDE.includes(repo.full_name)) {
      continue;
    }

    reposByFullName.set(repo.full_name, repo);
  }

  const projects = Array.from(reposByFullName.values())
    .map(repoToProject)
    .sort((a, b) => new Date(b.updatedAt) - new Date(a.updatedAt));

  const output = {
    _note: "This file is auto-generated by GitHub Actions. Run: node scripts/fetch-projects.js",
    _fetchedAt: new Date().toISOString(),
    _org: ORG,
    _extraRepos: EXTRA_REPOS,
    projects
  };

  fs.mkdirSync(path.dirname(OUTPUT), { recursive: true });
  fs.writeFileSync(OUTPUT, JSON.stringify(output, null, 2));

  console.log(`✅ Wrote ${projects.length} projects to ${OUTPUT}`);
  console.log(`   Projects: ${projects.map(p => p.fullName || p.name).join(', ')}`);
}

fetchRepos().catch(err => {
  console.error('❌ Failed to fetch projects:', err.message);
  process.exit(1);
});
